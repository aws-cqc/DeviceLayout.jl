"""
    GetBoundary(source; kwargs...)
    GetBoundary(destination, source; kwargs...)

Extract the boundary of `source`, in place or into `destination`, which must be new or
`source`.

# Keywords

  - `combined`: If `true`, return the boundary of the combined shape rather than of each
    entity. Default is `true`.
  - `oriented`: If `true`, orient the boundary entities. Default is `true`.
  - `recursive`: If `true`, return boundaries recursively down to points. Default is `false`.
  - `direction`: `"x"`, `"y"`, or `"z"` (case-insensitive) to return only boundaries
    perpendicular to that axis, or `"all"`. Default is `"all"`.
  - `position`: `"min"` or `"max"` to return only boundaries at that end of `direction`, or
    `"all"`. Default is `"all"`.
"""
struct GetBoundary <: LayerOp
    destination::Symbol
    source::Symbol
    combined::Bool
    oriented::Bool
    recursive::Bool
    direction::String
    position::String
    function GetBoundary(
        destination::Symbol,
        source::Symbol,
        combined::Bool,
        oriented::Bool,
        recursive::Bool,
        direction::AbstractString,
        position::AbstractString
    )
        direction = lowercase(direction)
        position = lowercase(position)
        direction in ("all", "x", "y", "z") ||
            throw(ArgumentError("GetBoundary direction must be all, x, y, or z"))
        position in ("all", "min", "max") ||
            throw(ArgumentError("GetBoundary position must be all, min, or max"))
        return new(destination, source, combined, oriented, recursive, direction, position)
    end
end
function GetBoundary(
    destination::Symbol,
    source::Symbol;
    combined::Bool=true,
    oriented::Bool=true,
    recursive::Bool=false,
    direction::AbstractString="all",
    position::AbstractString="all"
)
    return GetBoundary(
        destination,
        source,
        combined,
        oriented,
        recursive,
        direction,
        position
    )
end
GetBoundary(source::Symbol; kwargs...) = GetBoundary(source, source; kwargs...)

const _EXTERIOR_BOUNDARY_LAYERS = Dict(
    ("X", "min") => :EXTBND_XMIN,
    ("X", "max") => :EXTBND_XMAX,
    ("Y", "min") => :EXTBND_YMIN,
    ("Y", "max") => :EXTBND_YMAX,
    ("Z", "min") => :EXTBND_ZMIN,
    ("Z", "max") => :EXTBND_ZMAX
)

"""
    exterior_boundaries(bounding_volume::Symbol) -> Vector{GetBoundary}

Return operations extracting the six axis-aligned exterior faces of `bounding_volume`
into layers `:EXTBND_XMIN`, `:EXTBND_XMAX`, `:EXTBND_YMIN`, `:EXTBND_YMAX`, `:EXTBND_ZMIN`,
and `:EXTBND_ZMAX`.
"""
function exterior_boundaries(bounding_volume_layer::Symbol)
    operations = GetBoundary[]
    for direction in ("X", "Y", "Z"), position in ("min", "max")
        destination = _EXTERIOR_BOUNDARY_LAYERS[(direction, position)]
        push!(
            operations,
            GetBoundary(destination, bounding_volume_layer; direction, position)
        )
    end
    return operations
end

