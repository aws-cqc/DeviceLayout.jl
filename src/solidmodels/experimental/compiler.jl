# Physical groups of a layer, their dimension, and the extrusion distance in STP units once
# extruded. Until rendering, every layer holds exactly one PG, named after the layer; the
# post-render passes (locator selection, deduplication) add further PGs.
mutable struct LayerState
    pgs::Vector{String}
    dim::Int
    dz::Union{Nothing, Float64}
end
LayerState(pgs::Vector{String}, dim::Int) = LayerState(pgs, dim, nothing)

const LayerRegistry = Dict{Symbol, LayerState}

# Internal supertypes for typed layer-level operations.
abstract type LayerOp end
abstract type BooleanOp <: LayerOp end

"""
    Extrude(source; kwargs...)
    Extrude(source, dz)
    Extrude(destination, source; kwargs...)
    Extrude(destination, source, dz)

Extrude a 1D or 2D layer along z, in place or into `destination`. By default, a [`SourceStack`](@ref)
layer is extruded to its declared thickness or level span. Generated layers (i.e. layers
not present in the source stack but generated by operations) need `dz` or `to_level`.

# Keywords

  - `to_level`: Chiplet assembly level to extrude to. The source geometry must be planar.
  - `offset`: Displacement from `to_level`.
"""
struct Extrude <: LayerOp
    destination::Symbol
    source::Symbol
    dz::Union{Nothing, Coordinate}
    to_level::Union{Nothing, Int}
    offset::Union{Nothing, Coordinate}
    function Extrude(
        destination::Symbol,
        source::Symbol,
        dz::Union{Nothing, Coordinate},
        to_level::Union{Nothing, Int},
        offset::Union{Nothing, Coordinate}
    )
        !isnothing(dz) &&
            !isnothing(to_level) &&
            throw(ArgumentError("Extrude accepts either dz or to_level, not both"))
        isnothing(to_level) &&
            !isnothing(offset) &&
            throw(ArgumentError("Extrude offset requires to_level"))
        return new(destination, source, dz, to_level, offset)
    end
end
Extrude(destination::Symbol, source::Symbol; to_level=nothing, offset=nothing) =
    Extrude(destination, source, nothing, to_level, offset)
Extrude(destination::Symbol, source::Symbol, dz::Coordinate) =
    Extrude(destination, source, dz, nothing, nothing)
Extrude(source::Symbol; kwargs...) = Extrude(source, source; kwargs...)
Extrude(source::Symbol, dz::Coordinate) = Extrude(source, source, dz)

"""
    Cut(destination, object, tools; kwargs...)

Subtract `tools` from `object`. `tools` can be a single layer symbol or a collection of them.
`destination` must be new or one of the inputs, and `object` must not be one of the tools.

# Keywords

  - `remove_object`: If `true`, consume `object`. Default is `false`.
  - `remove_tool`: If `true`, consume every tool. Required if `destination` is one of several
    tools. Default is `false`.
"""
struct Cut{N} <: BooleanOp
    destination::Symbol
    object::Symbol
    tools::NTuple{N, Symbol}
    remove_object::Bool
    remove_tool::Bool
    function Cut{N}(destination, object, tools, remove_object, remove_tool) where {N}
        iszero(N) && throw(ArgumentError("Cut requires at least one tool layer"))
        # Subtracting a layer from itself always leaves nothing.
        object in tools && throw(ArgumentError("Cut object must not be one of its tools"))
        if N > 1 && destination in tools && !remove_tool
            throw(
                ArgumentError(
                    "Cut(:$destination, :$object, ...): replacing one of several tools " *
                    "consumes all of them; set `remove_tool=true` or use a new destination"
                )
            )
        end
        remove_object &&
            destination == object &&
            @warn "Cut(:$destination, :$object, ...): `remove_object=true` is ignored " *
                  "because the object is replaced in place."
        remove_tool &&
            tools == (destination,) &&
            @warn "Cut(:$destination, :$object, ...): `remove_tool=true` is ignored " *
                  "because a tool is replaced in place."
        return new{N}(destination, object, tools, remove_object, remove_tool)
    end
end
function Cut(
    dest::Symbol,
    object::Symbol,
    tools::NTuple{N, Symbol};
    remove_object::Bool=false,
    remove_tool::Bool=false
) where {N}
    return Cut{N}(dest, object, tools, remove_object, remove_tool)
end
Cut(dest::Symbol, object::Symbol, tool::Symbol; kwargs...) =
    Cut(dest, object, (tool,); kwargs...)
Cut(dest::Symbol, object::Symbol, tools::AbstractVector{Symbol}; kwargs...) =
    Cut(dest, object, Tuple(tools); kwargs...)

"""
    Fuse(source)
    Fuse(destination, sources; kwargs...)

Union `sources` into `destination`. `sources` can be a single layer symbol or a collection
of them. `destination` must be new or one of the sources. `Fuse(source)` merges overlapping
geometry of `source` in place.

# Keywords

  - `remove_sources`: If `true`, consume every source. Required if `destination` is one of
    several sources. Default is `false`.
"""
struct Fuse{N} <: BooleanOp
    destination::Symbol
    sources::NTuple{N, Symbol}
    remove_sources::Bool
    function Fuse{N}(destination, sources, remove_sources) where {N}
        iszero(N) && throw(ArgumentError("Fuse requires at least one source layer"))
        allunique(sources) || throw(ArgumentError("Fuse source layers must be unique"))
        N > 1 &&
            destination in sources &&
            !remove_sources &&
            throw(
                ArgumentError(
                    "Fuse(:$destination, ...): replacing one of several sources consumes " *
                    "all of them; set `remove_sources=true` or use a new destination"
                )
            )
        remove_sources &&
            sources == (destination,) &&
            @warn "Fuse(:$destination): `remove_sources=true` is ignored because healing " *
                  "a layer in place always consumes it."
        return new{N}(destination, sources, remove_sources)
    end
end
Fuse(dest::Symbol, sources::NTuple{N, Symbol}; remove_sources::Bool=false) where {N} =
    Fuse{N}(dest, sources, remove_sources)
Fuse(dest::Symbol, sources::AbstractVector{Symbol}; kwargs...) =
    Fuse(dest, Tuple(sources); kwargs...)
Fuse(source::Symbol; kwargs...) = Fuse(source, (source,); kwargs...)

"""
    Intersect(destination, object, tool; kwargs...)

Compute the intersection of `object` and `tool` and assign to `destination`, which must be
new or one of the inputs. The result has the lower of the input dimensions.

# Keywords

  - `remove_object`: If `true`, consume `object`. Default is `false`.
  - `remove_tool`: If `true`, consume `tool`. Default is `false`.
"""
struct Intersect <: BooleanOp
    destination::Symbol
    object::Symbol
    tool::Symbol
    remove_object::Bool
    remove_tool::Bool
    function Intersect(
        destination::Symbol,
        object::Symbol,
        tool::Symbol;
        remove_object::Bool=false,
        remove_tool::Bool=false
    )
        object == tool &&
            throw(ArgumentError("Intersect requires distinct object and tool layers"))
        remove_object &&
            destination == object &&
            @warn "Intersect(:$destination, :$object, :$tool): `remove_object=true` is " *
                  "ignored because the object is replaced in place and always consumed."
        remove_tool &&
            destination == tool &&
            @warn "Intersect(:$destination, :$object, :$tool): `remove_tool=true` is " *
                  "ignored because the tool is replaced in place and always consumed."
        return new(destination, object, tool, remove_object, remove_tool)
    end
end

"""
    GetInterface(destination, object, tool)

Compute the interface between `object` and `tool` and assign to `destination`, which
must be new. The interface of inputs of equal dimension is one dimension lower; otherwise it
has the lower input dimension.
"""
struct GetInterface <: BooleanOp
    destination::Symbol
    object::Symbol
    tool::Symbol
    function GetInterface(destination::Symbol, object::Symbol, tool::Symbol)
        destination in (object, tool) && throw(
            ArgumentError("GetInterface destination must differ from its input layers")
        )
        return new(destination, object, tool)
    end
end

